'use strict';
const path = require('path');
const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch({ channel: 'chrome', headless: true, args: ['--autoplay-policy=no-user-gesture-required','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'] });
  const p = await b.newPage({ viewport: { width: 960, height: 540 } });
  const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => { if (m.type() === 'error') errs.push(m.text().slice(0,200)); });
  await p.goto('file:///' + path.resolve(__dirname, '..', 'film', 'index.html').replace(/\\/g, '/') + '?autostart=1', { waitUntil: 'load' });
  await p.waitForTimeout(1200);
  await p.evaluate(() => window.FILM.play());
  await p.waitForTimeout(6000);
  const a = await p.evaluate(() => ({ t: +window.TEST_AUDIO.currentTime.toFixed(2), paused: window.TEST_AUDIO.paused, err: window.TEST_AUDIO.error ? window.TEST_AUDIO.error.code : null }));
  await p.evaluate(() => window.FILM.freeze(211.9));
  await p.waitForTimeout(300);
  await p.screenshot({ path: path.resolve(__dirname, '..', 'frames', 'film', 'final_end.png') });
  await p.evaluate(() => window.FILM.freeze(29.8));
  await p.waitForTimeout(300);
  await p.screenshot({ path: path.resolve(__dirname, '..', 'frames', 'film', 'final_cut.png') });
  console.log(JSON.stringify(a), 'errors', errs.length ? errs.slice(0,4).join(' | ') : 'none');
  await b.close();
})().catch(e => { console.error('FAILED', e.message); process.exit(1); });
