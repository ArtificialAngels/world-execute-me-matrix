/* _build/gen-world.js — anchors -> src/01_world.js */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const A = require('./world-anchors');

function fmtK(K) {
  return '[' + K.map(p => '[' + p[0] + ',' + p[1] + ']').join(',') + ']';
}

const lines = [];
lines.push('/* GENERATED by _build/gen-world.js from _build/world-anchors.js — do not edit. */');
lines.push('window.EM = window.EM || {};');
lines.push('EM.World = (function () {');
lines.push('  var P = {');
const pk = Object.keys(A.params);
pk.forEach((k, i) => lines.push('    ' + k + ': ' + fmtK(A.params[k]) + (i < pk.length - 1 ? ',' : '')));
lines.push('  };');
lines.push('  var LAMP = {');
const lk = Object.keys(A.lamp);
lk.forEach((k, i) => lines.push('    ' + k + ': ' + fmtK(A.lamp[k]) + (i < lk.length - 1 ? ',' : '')));
lines.push('  };');
lines.push(`
  var clamp = EM.clamp, smoothstep = EM.smoothstep;
  function sample(K, t) {
    if (t <= K[0][0]) return K[0][1];
    var n = K.length;
    if (t >= K[n - 1][0]) return K[n - 1][1];
    var lo = 0, hi = n - 1;
    while (lo <= hi) {
      var mid = (lo + hi) >> 1;
      if (K[mid][0] <= t) lo = mid + 1; else hi = mid - 1;
    }
    var a = K[hi], b = K[hi + 1];
    var u = (t - a[0]) / Math.max(1e-6, b[0] - a[0]);
    return a[1] + (b[1] - a[1]) * smoothstep(clamp(u, 0, 1));
  }
  function at(t) {
    var w = { t: t };
    for (var k in P) w[k] = sample(P[k], t);
    w.lamp = {
      x: sample(LAMP.x, t), y: sample(LAMP.y, t), z: sample(LAMP.z, t),
      lux: sample(LAMP.lux, t), k: sample(LAMP.k, t)
    };
    w.pal = EM.PAL(w);
    return w;
  }
  return { at: at, P: P, LAMP: LAMP, sample: sample };
})();
`);
const out = lines.join('\n') + '\n';
fs.writeFileSync(path.join(ROOT, 'src', '01_world.js'), out, 'utf8');
console.log('  wrote src/01_world.js  (' + out.length + ' bytes, ' + pk.length + ' params, ' + lk.length + ' lamp tracks)');
