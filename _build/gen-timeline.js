/* _build/gen-timeline.js — cue sheet -> assets/timeline.js + assets/lrc-embed.txt */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const SHEET = require('./cue-sheet');

function loadOnsets() {
  const p = path.join(ROOT, 'assets', 'onsets.js');
  if (!fs.existsSync(p)) return [];
  const src = fs.readFileSync(p, 'utf8');
  const m = src.match(/EM\.ONSETS\s*=\s*(\[[\s\S]*\]);/);
  if (!m) return [];
  try { return new Function('return ' + m[1])(); } catch (e) { console.error('onsets parse failed', e.message); return []; }
}

function main() {
  const rows = SHEET.cues.map(r => r.slice());
  const onsets = loadOnsets();

  /* snap a cue to the nearest real onset, within 0.30 s, keeping order */
  let snapped = 0;
  if (onsets.length) {
    let prev = -1;
    for (const r of rows) {
      const wantSnap = SHEET.snapToOnset.some(p => String(r[2]).indexOf(p) === 0);
      if (!wantSnap) { prev = r[0]; continue; }
      const target = r[0] * 1000;
      let best = null, bestD = 1e9;
      for (const o of onsets) {
        if (o[2] < 0.68) continue;   /* only accents, not every ghost note */
        const d = Math.abs(o[0] - target);
        if (d < bestD) { bestD = d; best = o[0]; }
      }
      if (best != null && bestD <= 300 && best / 1000 > prev - 1e-6) {
        r[0] = Math.round(best) / 1000;
        snapped++;
      }
      prev = r[0];
    }
  }

  /* validate */
  const problems = [];
  const seen = new Set();
  for (let i = 0; i < rows.length; i++) {
    const r = rows[i];
    if (typeof r[0] !== 'number' || !isFinite(r[0])) problems.push('bad time at ' + i);
    if (i && rows[i][0] <= rows[i - 1][0]) problems.push('cue ' + i + ' does not advance (' + rows[i - 1][0] + ' -> ' + rows[i][0] + ')');
    if (!r[1]) problems.push('empty text at ' + i);
    if (!r[2]) problems.push('empty scene at ' + i);
    if (seen.has(r[2])) problems.push('scene id twice: ' + r[2]);
    seen.add(r[2]);
    for (let k = 3; k <= 5; k++) if (r[k] === undefined) problems.push('short row at ' + i);
  }

  const js = '/* GENERATED by _build/gen-timeline.js — do not edit. */\n' +
    'window.EM = window.EM || {};\n' +
    'EM.CUES = [\n' + rows.map(r =>
      '  [' + r[0].toFixed(3) + ',' + JSON.stringify(r[1]) + ',' + JSON.stringify(r[2]) + ',' + r[3] + ',' + r[4] + ',' + JSON.stringify(r[5]) + ']'
    ).join(',\n') + '\n];\n' +
    'EM.HOLD = {};\n' +
    'EM.TIMELINE_META = { count: ' + rows.length + ', snapped: ' + snapped + ' };\n';
  fs.writeFileSync(path.join(ROOT, 'assets', 'timeline.js'), js, 'utf8');

  /* second, independent copy embedded in index.html (self-test compares) */
  const embed = rows.map(r => {
    const t = r[0], m = Math.floor(t / 60), s = t - m * 60;
    const ss = (s < 10 ? '0' : '') + s.toFixed(3);
    return '[' + m + ':' + ss + ']' + r[1] + '\t' + (r[5] || '');
  }).join('\n') + '\n';
  fs.writeFileSync(path.join(ROOT, 'assets', 'lrc-embed.txt'), embed, 'utf8');

  console.log('  cues        : ' + rows.length);
  console.log('  snapped     : ' + snapped + ' / ' + rows.filter(r => SHEET.snapToOnset.some(p => String(r[2]).indexOf(p) === 0)).length);
  console.log('  first / last: ' + rows[0][0].toFixed(3) + ' s / ' + rows[rows.length - 1][0].toFixed(3) + ' s');
  if (problems.length) {
    console.error('CUE SHEET PROBLEMS:');
    problems.forEach(p => console.error('  x ' + p));
    process.exit(1);
  }
  console.log('  timeline OK');
}
main();
